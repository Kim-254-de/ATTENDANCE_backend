import fs from 'node:fs';
import type { Response } from 'express';
import PDFDocument from 'pdfkit';
import { env } from '../../config/env.js';

/**
 * Shared "chrome" for every generated report in this service: a cover page
 * (title, who generated it and when, the filters applied) and a footer
 * stamped on every later page with the same generation timestamp and the
 * institution name. The footer exists because these reports may eventually
 * be handed to an External Quality Assurance reviewer — a page detached
 * from its cover should still say what it is and when it was produced.
 *
 * Content beyond this chrome (tables, figures) is drawn by each module's own
 * export service on top of the page this returns.
 */

export interface ReportOptions {
  title: string;
  subtitle?: string;
  generatedBy: string;
  filtersApplied?: Record<string, string | undefined>;
}

const MARGIN = 50;

function formatFilterLines(filters?: Record<string, string | undefined>): string[] {
  if (!filters) return [];
  return Object.entries(filters)
    .filter((entry): entry is [string, string] => Boolean(entry[1]))
    .map(([key, value]) => `${key}: ${value}`);
}

/**
 * Draws text inside the bottom margin. PDFKit treats the margin as off-limits
 * for text flow and auto-inserts a new page the instant it looks like content
 * has run past `page.height - margins.bottom` — which the footer always has,
 * by definition. Zeroing the bottom margin for the duration of this call (and
 * resetting the cursor to the top afterwards) is what stops that from firing
 * the `pageAdded` listener again recursively, which otherwise overflows the
 * call stack within a few pages.
 */
function drawFooter(doc: PDFKit.PDFDocument, pageNumber: number, generatedAtLabel: string): void {
  const { top, bottom: bottomMargin } = doc.page.margins;
  const y = doc.page.height - MARGIN + 12;

  doc.page.margins.bottom = 0;
  doc
    .fontSize(8)
    .fillColor('#6b7280')
    .text(`${env.QA_INSTITUTION_NAME} — Generated ${generatedAtLabel} — Page ${pageNumber}`, MARGIN, y, {
      width: doc.page.width - MARGIN * 2,
      align: 'center',
      lineBreak: false,
    })
    .fillColor('#111827');
  doc.page.margins.bottom = bottomMargin;

  // Whatever is drawn next (this page's real content, after `pageAdded`
  // fires) must resume at the top, not wherever the footer left the cursor.
  doc.x = doc.page.margins.left;
  doc.y = top;
}

/** Opens a new report document positioned at the start of its first content page, after drawing the cover page. */
export function createReportDocument(opts: ReportOptions): PDFKit.PDFDocument {
  const doc = new PDFDocument({ margin: MARGIN });
  const generatedAt = new Date();
  const generatedAtLabel = `${generatedAt.toISOString().replace('T', ' ').slice(0, 19)} UTC`;

  let pageNumber = 1;
  doc.on('pageAdded', () => {
    pageNumber += 1;
    drawFooter(doc, pageNumber, generatedAtLabel);
  });

  if (env.QA_REPORT_LOGO_PATH && fs.existsSync(env.QA_REPORT_LOGO_PATH)) {
    try {
      doc.image(env.QA_REPORT_LOGO_PATH, MARGIN, MARGIN, { fit: [120, 60] });
      doc.moveDown(5);
    } catch {
      // A broken logo path must never fail report generation.
    }
  }

  doc.fontSize(10).fillColor('#6b7280').text(env.QA_INSTITUTION_NAME.toUpperCase());
  doc.moveDown(1.5);
  doc.fontSize(22).fillColor('#111827').text(opts.title);
  if (opts.subtitle) {
    doc.fontSize(13).fillColor('#374151').text(opts.subtitle);
  }
  doc.moveDown(1);
  doc.fontSize(10).fillColor('#6b7280').text(`Generated by ${opts.generatedBy} on ${generatedAtLabel}`);

  const filterLines = formatFilterLines(opts.filtersApplied);
  if (filterLines.length > 0) {
    doc.moveDown(1);
    doc.fontSize(11).fillColor('#111827').text('Filters applied:');
    doc.fontSize(10).fillColor('#374151').list(filterLines);
  }

  doc.moveDown(2);
  doc
    .fontSize(9)
    .fillColor('#9ca3af')
    .text('CONFIDENTIAL — Internal Quality Assurance. Not for external distribution without authorisation.');

  drawFooter(doc, pageNumber, generatedAtLabel);
  doc.fillColor('#111827');

  doc.addPage();
  return doc;
}

/**
 * Table header/row helper: fixed-width columns that wrap rather than
 * truncate. The row's height is measured from the tallest wrapped cell
 * (`heightOfString`) rather than assumed to be one line, so a long value
 * that wraps to two or three lines never overlaps the row drawn after it —
 * `doc.moveDown()`'s fixed step does not know about wrapped height. `doc.x`
 * is reset to the left margin afterwards so whatever is drawn next (another
 * row, or a heading) is not left starting from the last column's x position.
 */
export function drawTableRow(
  doc: PDFKit.PDFDocument,
  columns: Array<{ text: string; width: number }>,
  options: { bold?: boolean; fontSize?: number; color?: string } = {},
): void {
  doc.font(options.bold ? 'Helvetica-Bold' : 'Helvetica');
  doc.fontSize(options.fontSize ?? 9).fillColor(options.color ?? '#111827');

  const y = doc.y;
  const rowHeight = Math.max(...columns.map((c) => doc.heightOfString(c.text, { width: c.width })));

  let x = doc.page.margins.left;
  for (const column of columns) {
    doc.text(column.text, x, y, { width: column.width });
    x += column.width;
  }

  doc.x = doc.page.margins.left;
  doc.y = y + rowHeight + 4;
  doc.fillColor('#111827');
}

/** Pipes the document straight to the response and ends it; the caller does not touch `res` afterwards. */
export function streamPdfToResponse(doc: PDFKit.PDFDocument, res: Response, filename: string): void {
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
  doc.pipe(res);
  doc.end();
}
